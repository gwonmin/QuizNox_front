/**
 * MDX에서 검색용 요약·소제목·짧은 인용문을 뽑아
 * src/constants/handbookDocExcerpts.ts 를 다시 씁니다.
 *
 *   node scripts/build-handbook-excerpts.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const viewPath = path.join(root, "src/pages/Handbook/HandbookView.tsx");
const mdxRoot = path.join(root, "src/pages/Handbook/mdx");
const outPath = path.join(root, "src/constants/handbookDocExcerpts.ts");

const view = fs.readFileSync(viewPath, "utf8");

const importMap = new Map();
for (const match of view.matchAll(
  /import\s+(\w+)\s+from\s+"\.\/mdx\/([^"]+)\.mdx"/g,
)) {
  importMap.set(match[1], match[2]);
}

const docs = [];
const seen = new Set();
for (const match of view.matchAll(
  /layerId === "([^"]+)" && slug === "([^"]+)"[\s\S]{0,220}?return <(\w+)/g,
)) {
  const layerId = match[1];
  const slug = match[2];
  const component = match[3];
  const key = `${layerId}/${slug}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const rel = importMap.get(component);
  if (!rel) {
    console.warn(`import 없음: ${component} (${key})`);
    continue;
  }
  docs.push({ key, file: path.join(mdxRoot, `${rel}.mdx`) });
}

function unescapeQuoted(value) {
  return value.replace(/\\"/g, '"').replace(/\\n/g, " ").trim();
}

function extractLead(source) {
  const match = source.match(/\blead="((?:\\.|[^"\\])*)"/);
  return match ? unescapeQuoted(match[1]) : "";
}

function stripFences(source) {
  return source.replace(/```[\s\S]*?```/g, "");
}

function extractHeadings(source) {
  const headings = [];
  for (const match of stripFences(source).matchAll(/^#{2,3}\s+(.+)$/gm)) {
    const title = match[1].replace(/[*_`]/g, "").replace(/\s+/g, " ").trim();
    if (title) headings.push(title);
  }
  return headings;
}

function extractLines(source, lead) {
  const withoutImports = source.replace(/^import .+$/gm, "");
  const withoutFences = stripFences(withoutImports);
  const lines = [];
  const seenLine = new Set();
  for (const match of withoutFences.matchAll(/"((?:\\.|[^"\\])*)"/g)) {
    const text = unescapeQuoted(match[1]).replace(/\s+/g, " ");
    if (text.length < 12 || text.length > 180) continue;
    if (text === lead) continue;
    if (text.includes("@/") || text.includes("className") || text.startsWith("./")) continue;
    if (/^[\w.-]+$/.test(text)) continue;
    if (seenLine.has(text)) continue;
    seenLine.add(text);
    lines.push(text);
    if (lines.length >= 30) break;
  }
  return lines;
}

/** 본문에만 있는 짧은 한국어 단어. 스니펫에는 쓰지 않고 검색 매칭에만 씁니다. */
function extractTerms(source) {
  const withoutImports = source.replace(/^import .+$/gm, "");
  const seen = new Set();
  const terms = [];
  for (const match of stripFences(withoutImports).matchAll(/\p{Script=Hangul}{2,}/gu)) {
    const term = match[0];
    if (seen.has(term)) continue;
    seen.add(term);
    terms.push(term);
    if (terms.length >= 80) break;
  }
  return terms;
}

const excerpts = {};
let withLead = 0;
let missingFile = 0;

for (const doc of docs) {
  if (!fs.existsSync(doc.file)) {
    missingFile += 1;
    console.warn(`파일 없음: ${doc.file}`);
    continue;
  }
  const source = fs.readFileSync(doc.file, "utf8");
  const excerpt = extractLead(source);
  if (excerpt) withLead += 1;
  excerpts[doc.key] = {
    excerpt,
    headings: extractHeadings(source),
    lines: extractLines(source, excerpt),
    terms: extractTerms(source),
  };
}

const body = `// Generated by scripts/build-handbook-excerpts.mjs — 직접 고치지 마세요.
// SectionSummary lead, 소제목, 본문 인용문을 핸드북 검색에 씁니다.

export interface HandbookDocExcerpt {
  excerpt: string;
  headings: string[];
  lines: string[];
  terms: string[];
}

export const HANDBOOK_DOC_EXCERPTS: Record<string, HandbookDocExcerpt> = ${JSON.stringify(excerpts, null, 2)};
`;

fs.writeFileSync(outPath, body);
console.log(
  `docs ${Object.keys(excerpts).length}, lead ${withLead}, missing file ${missingFile}`,
);

if (Object.keys(excerpts).length < 160) {
  throw new Error("문서 매핑이 너무 적습니다. HandbookView 패턴을 확인하세요.");
}
